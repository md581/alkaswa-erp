export const formatCurrency = (amount: number, lang: 'en' | 'bn') => {
  // Traditional South Asian numbering system formatter (Lakh, Crore)
  // Let's create a custom function that matches BDT notation
  const bdtSymbol = "৳";
  if (lang === 'bn') {
    if (amount >= 10000000) {
      return `${bdtSymbol}${(amount / 10000000).toFixed(2)} কোটি`;
    } else if (amount >= 100000) {
      return `${bdtSymbol}${(amount / 100000).toFixed(2)} লক্ষ`;
    }
    return `${bdtSymbol}${amount.toLocaleString('bn-BD')}`;
  } else {
    if (amount >= 10000000) {
      return `${bdtSymbol}${(amount / 10000000).toFixed(2)} Crore`;
    } else if (amount >= 100000) {
      return `${bdtSymbol}${(amount / 100000).toFixed(2)} Lakh`;
    }
    return `${bdtSymbol}${amount.toLocaleString('en-US')}`;
  }
};

